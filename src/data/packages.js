// ── Lookups & helpers ────────────────────────────────────────────────────

export const packagesBySlug = new Map(packages.map((p) => [p.slug, p]));

export function getPackage(slug) {
  return packagesBySlug.get(slug);
}

export function getFeaturedPackages(limit = 6) {
  return packages.filter((p) => p.featured).slice(0, limit);
}

export function getPackagesByPurpose(purpose) {
  return packages.filter((p) => p.purpose === purpose);
}

/** Packages that visit a given destination slug. */
export function getPackagesForDestination(destinationSlug, limit = 3) {
  return packages.filter((p) => p.destinations.includes(destinationSlug)).slice(0, limit);
}

/** Filter the catalogue. Any argument left undefined is ignored. */
export function filterPackages({ purpose, tier, priceBand, region } = {}) {
  return packages.filter((p) => {
    if (purpose && p.purpose !== purpose) return false;
    if (tier && p.tier !== tier) return false;
    if (region && p.region !== region) return false;
    if (priceBand && (p.priceFrom < priceBand.min || p.priceFrom >= priceBand.max)) return false;
    return true;
  });
}

/** Lowest advertised price, used for "packages from ₹X" copy. */
export function getLowestPrice() {
  return Math.min(...packages.map((p) => p.priceFrom));
}
