// ── Lookups & helpers ────────────────────────────────────────────────────

export const destinationsBySlug = new Map(destinations.map((d) => [d.slug, d]));

export function getDestination(slug) {
  return destinationsBySlug.get(slug);
}

export function getFeaturedDestinations(limit = 3) {
  return destinations.filter((d) => d.featured).slice(0, limit);
}

export function getDestinationsByCollection(collection) {
  return destinations.filter((d) => d.collection === collection);
}

/** Filter the catalogue. Any argument left undefined is ignored. */
export function filterDestinations({ region, environment, theme, collection } = {}) {
  return destinations.filter((d) => {
    if (region && d.region !== region) return false;
    if (environment && d.environment !== environment) return false;
    if (theme && !d.themes.includes(theme)) return false;
    if (collection && d.collection !== collection) return false;
    return true;
  });
}

/** Destinations sharing a collection or environment, excluding the current one. */
export function getRelatedDestinations(slug, limit = 3) {
  const current = getDestination(slug);
  if (!current) return [];
  const scored = destinations
    .filter((d) => d.slug !== slug)
    .map((d) => {
      let score = 0;
      if (d.collection === current.collection) score += 3;
      if (d.environment === current.environment) score += 2;
      score += d.themes.filter((t) => current.themes.includes(t)).length;
      return { d, score };
    })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map(({ d }) => d);
}
